def all_metrics(computations):
    """Список всех метрик дашборда: базовые, встроенные формулы и добавленные пользователем."""
    result = []
    for key, info in MEASURES.items():
        result.append({'id': key, 'title': info['title'], 'unit': info['unit'], 'kind': 'measure'})
    for f in BUILTIN_FORMULAS:
        result.append(f)
    for c in computations:
        result.append(c)
    return result


def metric_title(metric_id, computations):
    for m in all_metrics(computations):
        if m['id'] == metric_id:
            return m['title']
    return metric_id
